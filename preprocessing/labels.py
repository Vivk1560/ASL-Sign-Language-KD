"""Authoritative class mapping (``labels.json``).

Every manifest, report and later training script must take class indices from
the file produced here. A-Z always keep indices 0-25 regardless of class set.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from .config import ALPHABET, EXTRA_CLASSES, PreprocessConfig
from .records import read_json, write_json

SCHEMA_VERSION = 1


def canonical_class_name(folder_name: str) -> str | None:
    """Map a folder name to its canonical class name, or ``None`` if unexpected.

    Letters are upper-cased (``a`` -> ``A``); ``del``/``nothing``/``space`` are
    lower-cased. Anything else is not a known class folder.
    """
    name = folder_name.strip()
    if len(name) == 1 and name.upper() in ALPHABET:
        return name.upper()
    if name.lower() in EXTRA_CLASSES:
        return name.lower()
    return None


def build_labels(cfg: PreprocessConfig) -> dict[str, Any]:
    """Build the label mapping dictionary from the configuration."""
    classes = list(cfg.classes)
    return {
        "schema_version": SCHEMA_VERSION,
        "class_set": cfg.class_set,
        "num_classes": len(classes),
        "classes": classes,
        "class_to_idx": {name: i for i, name in enumerate(classes)},
        "idx_to_class": {str(i): name for i, name in enumerate(classes)},
        "excluded_classes": dict(cfg.excluded_classes),
        "source_dataset": cfg.kaggle_dataset,
        "note": "Authoritative mapping. Generated by preprocessing; do not edit by hand.",
    }


def write_labels(cfg: PreprocessConfig) -> Path:
    """Write ``labels.json`` into the metadata directory."""
    return write_json(cfg.labels_path, build_labels(cfg))


def load_labels(path: Path) -> dict[str, Any]:
    return read_json(path)


def labels_mismatches(labels: dict[str, Any], cfg: PreprocessConfig) -> list[str]:
    """Return human-readable differences between a labels dict and the config."""
    expected = build_labels(cfg)
    problems: list[str] = []
    for key in ("class_set", "num_classes", "classes", "class_to_idx"):
        if labels.get(key) != expected[key]:
            problems.append(f"labels.json '{key}' differs from configuration")
    return problems
